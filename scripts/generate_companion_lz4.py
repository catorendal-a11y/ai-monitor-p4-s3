"""Generate built-in LZ4 frames from the committed RGB565A8 artwork, using pinned LVGL."""
import argparse
import ctypes
import hashlib
from pathlib import Path
import re
import tempfile
from benchmark_asset_codecs import ROOT, build_codecs

POSES = ('work', 'done', 'low', 'critical', 'sleep', 'blink')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cc', default='gcc')
    args = parser.parse_args()
    source = (ROOT / 'src/ui/nova_assets.cpp').read_text(encoding='utf-8')
    lines = ['// Generated by scripts/generate_companion_lz4.py; built-in artwork only.',
             '#include "builtin_lz4.h"', 'namespace companions {']
    records = []
    total = 0
    with tempfile.TemporaryDirectory(prefix='builtin-lz4-') as temporary:
        codec = build_codecs(Path(temporary), args.cc)
        try:
            for orbit in (False, True):
                for index, pose in enumerate(POSES):
                    name = ('orbit_' if orbit else '') + pose
                    array = re.search(r'const uint8_t ' + name + r'_pixels\[\] = \{(.*?)\};', source, re.S)
                    geometry = re.search(r'const lv_image_dsc_t ' + name + r' = \{ \{LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565A8, 0, (\d+), (\d+),', source)
                    if not array or not geometry:
                        raise ValueError('Missing committed artwork: ' + name)
                    raw = bytes(int(value, 16) for value in re.findall(r'0x([0-9a-fA-F]{2})', array[1]))
                    width, height = map(int, geometry.groups())
                    if len(raw) != width * height * 3:
                        raise ValueError('Invalid pixel count: ' + name)
                    output = ctypes.create_string_buffer(codec.LZ4_compressBound(len(raw)))
                    length = codec.LZ4_compress_default(raw, output, len(raw), len(output))
                    if length <= 0:
                        raise ValueError('Compression failed')
                    encoded = output.raw[:length]
                    decoded = ctypes.create_string_buffer(len(raw))
                    if codec.LZ4_decompress_safe(encoded, decoded, length, len(raw)) != len(raw) or decoded.raw != raw:
                        raise ValueError('Round-trip failed')
                    symbol = name + '_lz4'
                    lines.append('static const uint8_t ' + symbol + '[]={')
                    for offset in range(0, length, 32):
                        lines.append(','.join(str(byte) for byte in encoded[offset:offset + 32]) + ',')
                    lines.append('};')
                    x, y = (58, 17) if orbit else (28, 0)
                    records.append('{ {Pose::' + pose + ',' + ','.join(map(str, (width, height, x, y, length, len(raw)))) +
                                   ',{},"' + hashlib.sha256(encoded).hexdigest() + '","' + hashlib.sha256(raw).hexdigest() + '"},' + symbol + '}')
                    total += length
            lines.extend(['const BuiltinFrame builtin_frames[12]={', ',\n'.join(records), '};', '}'])
            (ROOT / 'src/companions/builtin_lz4.cpp').write_text('\n'.join(lines) + '\n', encoding='ascii')
        finally:
            if __import__('os').name == 'nt':
                import _ctypes
                _ctypes.FreeLibrary(codec._handle)
    print('Verified 12 built-in LZ4 frames: ' + str(total) + ' bytes')


if __name__ == '__main__':
    main()
